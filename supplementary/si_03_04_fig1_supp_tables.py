# SUPPLEMENTARY SECTIONS 3 and 4 / SUPPLEMENTARY TABLES 3 and 4
# Standalone LaTeX tables of the per-model correlations behind Fig. 1 for
#   * words and phrases analysed separately (human concreteness)        -> Table 3
#   * GPT concreteness, phrases (Fig. 1b)                                -> extra table
#   * Lancaster perceptual strength: words, averaged phrases, pooled     -> Table 4
# The numbers themselves are computed by figure_01/figure_01_compute.py
# (fig1_per_model_correlations.csv, fig1_across_model_summary.csv): every scope
# (All / Wrd / Phr) for panels A and C is already in those files, so SI
# Sections 3-4 need no further computation. si_make_tex_tables.py writes the
# same two tables as \TabFigOneHuman / \TabFigOneLancaster macros plus the
# \FigOne* in-text macros (the form the manuscript actually \input's).
# ==============================================================================
import os, sys
import pandas as pd, numpy as np
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from paths import results
from registry import REGISTRY
F1 = results('figure_01'); OUT = results('si_03_04')
st = pd.read_csv(os.path.join(F1, 'fig1_per_model_correlations.csv')); su = pd.read_csv(os.path.join(F1, 'fig1_across_model_summary.csv'))
models = [n for n,_ in REGISTRY]
def cell(t, panel, scope, m):
    r = t[(t.panel==panel)&(t.scope==scope)&(t.model==m)]
    if r.empty: return ' & -- & -- & --'
    r = r.iloc[0]; dag = '' if r.bonf_sig else '$^{\\dagger}$'
    return f" & ${r.r:.3f}${dag} & [{r.ci_lo:.3f}, {r.ci_hi:.3f}] & {int(r.n):,}"
def mean_row(panel, scopes):
    out = '\\midrule\nMean across models'
    for sc in scopes:
        r = su[(su.panel==panel)&(su.scope==sc)].iloc[0]
        out += f" & ${r.mean_r:.3f}$ & [{r.ci_lo:.3f}, {r.ci_hi:.3f}] & "
    return out + ' \\\\'
def table(panel, scopes, heads, label, caption):
    L = ['\\begin{table}[!htbp]\\centering\\footnotesize', f'\\caption{{{caption}}}', f'\\label{{{label}}}',
         '\\setlength{\\tabcolsep}{4pt}', '\\begin{tabular}{l' + 'rcr'*len(scopes) + '}', '\\toprule',
         'Model' + ''.join(f' & \\multicolumn{{3}}{{c}}{{{h}}}' for h in heads) + ' \\\\',
         ''.join(f'\\cmidrule(lr){{{2+3*i}-{4+3*i}}}' for i in range(len(scopes))),
         ' ' + ' & $r$ & 95\\% CI & $n$'*len(scopes) + ' \\\\', '\\midrule']
    for m in models:
        L.append(m.replace('(', '(').replace('&','\\&') + ''.join(cell(st, panel, sc, m) for sc in scopes) + ' \\\\')
    L += [mean_row(panel, scopes), '\\bottomrule', '\\end{tabular}', '\\end{table}']
    return '\n'.join(L)
t3 = table('A', ['All','Wrd','Phr'], ['Pooled (Fig.~1a)','Words only','Phrases only'], 'tab:S-fig1-human',
  'The male abstraction bias replicates when words and phrases are analysed separately, across the 12 language models of Figs.~1 and 2. '
  'Two-tailed Pearson\'s correlations between the gender association of a term (positive, masculine) and human judgements of its concreteness, for each language model. '
  '$n$ is the number of rated terms scored by the model. The final row gives the unweighted mean across models with a 95\\% confidence interval across models. '
  '$^{\\dagger}$Not significant after Bonferroni correction for the number of models within the column. --, the model does not score this dataset.')
t4 = table('C', ['Wrd','Phr','All'], ['Words (Fig.~1c)','Phrases (averaged)','Words and phrases'], 'tab:S-fig1-lanc',
  'More masculine terms are lower in perceptual strength, for the single words in the original Lancaster Sensorimotor Norms (Fig.~1c) and for phrases when the norms are extended to them, across the 12 language models of Figs.~1 and 2. '
  'Two-tailed Pearson\'s correlations between the gender association of a term (positive, masculine) and its perceptual strength (mean rating across six perceptual modalities; 0--5), for each language model. '
  'For phrases, perceptual strength is the mean across the constituent words that appear in the norms. $n$ is the number of rated terms scored by the model. '
  'The final row gives the unweighted mean across models with a 95\\% confidence interval across models. $^{\\dagger}$Not significant after Bonferroni correction for the number of models within the column. --, the model does not score this dataset.')
tB = table('B', ['Phr'], ['GPT concreteness, phrases (Fig.~1b)'], 'tab:S-fig1-gpt',
  'The male abstraction bias replicates with concreteness ratings generated by GPT, across the 12 language models of Figs.~1 and 2. Two-tailed Pearson\'s correlations between the gender association of a phrase (positive, masculine) and its GPT-rated concreteness. '
  '$^{\\dagger}$Not significant after Bonferroni correction for the number of models.')
out = os.path.join(OUT, 'supp_tables_fig1_12models.tex')
open(out,'w').write('% Generated by si_03_04_fig1_supp_tables.py from fig1_per_model_correlations.csv (12-model registry)\n\n' + t3 + '\n\n' + tB + '\n\n' + t4 + '\n')
print(open(out).read()[:1500]); print('\nwritten', out)
