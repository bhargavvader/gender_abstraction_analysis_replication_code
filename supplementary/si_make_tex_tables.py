"""si_make_tex_tables.py  (= 06_make_tex.py, 5 Oct 2026)

Writes the two generated LaTeX files the manuscript \\input's:
  stats_fig1.tex     \\FigOne<Panel><Scope><Stat> macros (all Fig. 1 in-text statistics) + Supplementary Tables 3 and 4
                     as \\TabFigOneHuman / \\TabFigOneLancaster   <- from results/figure_01/ (figure_01_compute.py)
  stats_si_text.tex  Supplementary Tables 5-8 as \\TabTextCovWords / \\TabTextCovPhrases / \\TabTextCovPerModel /
                     \\TabTextComposition                           <- from results/si_05/ (si_05_lexical_covariates.py)
Formats follow the previous generated files. Output: results/tex/.
"""
import os, sys, numpy as np, pandas as pd
from scipy import stats
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from paths import results
from registry import REGISTRY
MODELS = [n for n, _ in REGISTRY]
F1 = results("figure_01"); R = results("si_05"); OUT = results("tex")
st = pd.read_csv(f"{F1}/fig1_per_model_correlations.csv"); su = pd.read_csv(f"{F1}/fig1_across_model_summary.csv")

def num(x, d=3): return f"${x:.{d}f}$"
def nfmt(n): return f"{int(n):,}".replace(",", "{,}")
def pfmt(p):
    if p >= 0.001: return f"$= {p:.3f}$"
    e = int(np.floor(np.log10(p))); m_ = p / 10**e
    return f"$= {m_:.1f}\\times10^{{{e}}}$"
def dag(sig): return "" if sig else "$^{\\dagger}$"

# ------------------------------------------------------------------ stats_fig1.tex --------------------------------
L = ["% =====================================================================",
     "% stats_fig1.tex -- GENERATED by figure_01_compute.py + si_make_tex_tables.py. Do not edit by hand.",
     "% Source: MASTER_all_models_gender_all_concreteness.csv (rebuilt with Wikipedia GloVe word scores); 12-model registry.",
     "% Macro names: \\FigOne<Panel A|B|C><Scope All|Wrd|Phr><Stat>",
     "% ====================================================================="]
for (panel, scope), t in st.groupby(["panel", "scope"], sort=False):
    s = su[(su.panel == panel) & (su.scope == scope)].iloc[0]; key = f"\\FigOne{panel}{scope}"
    L += [f"\\newcommand{{{key}MeanR}}{{{num(s.mean_r)}}}", f"\\newcommand{{{key}CIlo}}{{{num(s.ci_lo)}}}", f"\\newcommand{{{key}CIhi}}{{{num(s.ci_hi)}}}",
          f"\\newcommand{{{key}MinR}}{{{num(s.min_r)}}}", f"\\newcommand{{{key}MaxR}}{{{num(s.max_r)}}}",
          f"\\newcommand{{{key}KNeg}}{{{int(s.k_neg)}}}", f"\\newcommand{{{key}KSigNeg}}{{{int(s.k_sig_neg)}}}", f"\\newcommand{{{key}KSigPos}}{{{int(s.k_sig_pos)}}}",
          f"\\newcommand{{{key}KTot}}{{{int(s.k)}}}", f"\\newcommand{{{key}T}}{{{num(s.t, 2)}}}", f"\\newcommand{{{key}Df}}{{{int(s.df)}}}",
          f"\\newcommand{{{key}P}}{{{pfmt(s.p)}}}", f"\\newcommand{{{key}WilcP}}{{{pfmt(stats.wilcoxon(t.r).pvalue)}}}",
          f"\\newcommand{{{key}DecOne}}{{{num(s.dec1_mean, 2)}}}", f"\\newcommand{{{key}DecTen}}{{{num(s.dec10_mean, 2)}}}",
          f"\\newcommand{{{key}Nmin}}{{{nfmt(s.n_min)}}}", f"\\newcommand{{{key}Nmax}}{{{nfmt(s.n_max)}}}", ""]
def fig1_table(name, panel, scopes, heads):
    rows = [f"\\newcommand{{\\{name}}}{{%", "\\begingroup\\scriptsize\\setlength{\\tabcolsep}{1.9pt}%", "\\begin{tabular}{@{}lrcrrcrrcr@{}}", "\\toprule",
            " & " + " & ".join(f"\\multicolumn{{3}}{{c}}{{{h}}}" for h in heads) + " \\\\",
            "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\\cmidrule(lr){8-10}", "Model & " + " & ".join(["$r$ & 95\\% CI & $n$"] * 3) + " \\\\", "\\midrule"]
    for mname in MODELS:
        cells = []
        for sc in scopes:
            r = st[(st.panel == panel) & (st.scope == sc) & (st.model == mname)]
            if r.empty: cells.append("-- & -- & --"); continue
            r = r.iloc[0]; cells.append(f"{num(r.r)}{dag(r.bonf_sig)} & [{num(r.ci_lo)}, {num(r.ci_hi)}] & {nfmt(r.n)}")
        rows.append(f"{mname} & " + " & ".join(cells) + " \\\\")
    rows.append("\\midrule"); mean = []
    for sc in scopes:
        s = su[(su.panel == panel) & (su.scope == sc)].iloc[0]; mean.append(f"{num(s.mean_r)} & [{num(s.ci_lo)}, {num(s.ci_hi)}] & ")
    rows += ["\\textbf{Mean across models} & " + " & ".join(mean) + " \\\\", "\\bottomrule", "\\end{tabular}\\endgroup}", ""]
    return rows
L += fig1_table("TabFigOneHuman", "A", ["All", "Wrd", "Phr"], ["Pooled (Fig.~1a)", "Words only", "Phrases only"])
L += fig1_table("TabFigOneLancaster", "C", ["Wrd", "Phr", "All"], ["Words (Fig.~1c)", "Phrases (averaged)", "Words and phrases"])
open(f"{OUT}/stats_fig1.tex", "w").write("\n".join(L))

# ------------------------------------------------------------------ stats_si_text.tex -----------------------------
sw, sp = pd.read_csv(f"{R}/cov_summary_words.csv"), pd.read_csv(f"{R}/cov_summary_phrases.csv")
pw, pp = pd.read_csv(f"{R}/cov_per_model_words.csv"), pd.read_csv(f"{R}/cov_per_model_phrases.csv")
cw, cp = pd.read_csv(f"{R}/composition_words.csv"), pd.read_csv(f"{R}/composition_phrases.csv")
def rng(a, b): return f"{a:,}--{b:,}"
def cov_row(s): return f"{s.spec} & {num(s['mean'])} & [{num(s.ci_lo)}, {num(s.ci_hi)}] & {num(s['min'])} to {num(s['max'])} & {int(s.k_neg)}/{int(s.k)} & {int(s.k_sig_neg)} & {rng(int(s.n_min), int(s.n_max))} \\\\"
T = ["% =====================================================================",
     "% stats_si_text.tex -- GENERATED by si_05_lexical_covariates.py + si_make_tex_tables.py from the rebuilt",
     "% MASTER_all_models_gender_all_concreteness.csv with the 12-model registry shared by Figs. 1 and 2.",
     "% Do not edit by hand. Loaded by supplementary_results.tex.",
     "% ====================================================================="]
T += ["\\newcommand{\\TabTextCovWords}{%", "\\begingroup\\scriptsize\\setlength{\\tabcolsep}{3pt}%", "\\begin{tabular}{@{}p{6.4cm}cccccr@{}}", "\\toprule",
      "Specification & Mean $\\beta$ & 95\\% CI & Range & Negative & Sig. & $n$ per model \\\\", "\\midrule"]
blocks = {"A": "\\textit{A. Lexical covariates}", "B": "\\textit{B. Reliably rated words only}", "C": "\\textit{C. Within quintiles of word frequency}"}
last = None
for _, s in sw.iterrows():
    if s.block != last:
        if last is not None: T.append("\\addlinespace")
        T.append(f"\\multicolumn{{7}}{{l}}{{{blocks[s.block]}}} \\\\"); last = s.block
    T.append(cov_row(s))
T += ["\\bottomrule", "\\end{tabular}\\endgroup}", ""]
T += ["\\newcommand{\\TabTextCovPhrases}{%", "\\begingroup\\scriptsize\\setlength{\\tabcolsep}{3pt}%", "\\begin{tabular}{@{}p{6.4cm}cccccr@{}}", "\\toprule",
      "Specification & Mean $\\beta$ & 95\\% CI & Range & Negative & Sig. & $n$ per model \\\\", "\\midrule"]
T += [cov_row(s) for _, s in sp.iterrows()]; T += ["\\bottomrule", "\\end{tabular}\\endgroup}", ""]
# per-model table
WSPEC = {"None": sw.spec[0], "+ Freq.": "+ word frequency", "+ Length": "+ length (characters and syllables)", "+ VAD": "+ valence, arousal and dominance\\cite{warriner2013}",
         "+ All": "+ all of the above (frequency, length, polysemy, age of acquisition, valence, arousal, dominance, part of speech)"}
PSPEC = {"None": sp.spec[0], "+ Freq.": "+ word frequency (mean of constituent words)", "+ Length": "+ length (characters and number of words)",
         "+ POS": "+ part of speech (fixed effects)", "+ All": "+ all of the above"}
def cell(per, spec, mname, k):
    r = per[(per.spec == spec) & (per.model == mname)]
    if r.empty or pd.isna(r.iloc[0].beta): return "--"
    r = r.iloc[0]; return f"{num(r.beta)}{dag(r.p * k < 0.05)}"
T += ["\\newcommand{\\TabTextCovPerModel}{%", "\\begingroup\\scriptsize\\setlength{\\tabcolsep}{2.5pt}%", "\\begin{tabular}{@{}lcccccccccc@{}}", "\\toprule",
      " & \\multicolumn{5}{c}{Words} & \\multicolumn{5}{c}{Phrases} \\\\", "\\cmidrule(lr){2-6}\\cmidrule(lr){7-11}",
      "Model & " + " & ".join(WSPEC) + " & " + " & ".join(PSPEC) + " \\\\", "\\midrule"]
for mname in MODELS:
    T.append(f"{mname} & " + " & ".join(cell(pw, WSPEC[h], mname, 12) for h in WSPEC) + " & " + " & ".join(cell(pp, PSPEC[h], mname, 12) for h in PSPEC) + " \\\\")
T.append("\\midrule")
T.append("\\textbf{Mean across models} & " + " & ".join(num(sw[sw.spec == WSPEC[h]].iloc[0]["mean"]) for h in WSPEC) + " & " + " & ".join(num(sp[sp.spec == PSPEC[h]].iloc[0]["mean"]) for h in PSPEC) + " \\\\")
T += ["\\bottomrule", "\\end{tabular}\\endgroup}", ""]
# composition table
T += ["\\newcommand{\\TabTextComposition}{%", "\\begingroup\\scriptsize\\setlength{\\tabcolsep}{3pt}%", "\\begin{tabular}{@{}p{5.6cm}cccccc@{}}", "\\toprule",
      " & \\multicolumn{3}{c}{Words (12 models)} & \\multicolumn{3}{c}{Phrases (12 models)} \\\\", "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}",
      "Specification & Mean $\\beta$ & 95\\% CI & Neg. (sig.) & Mean $\\beta$ & 95\\% CI & Neg. (sig.) \\\\", "\\midrule"]
for (_, a), (_, b_) in zip(cw.iterrows(), cp.iterrows()):
    T.append(f"{a.spec} & {num(a['mean'])} & [{num(a.ci_lo)}, {num(a.ci_hi)}] & {int(a.k_neg)}/{int(a.k)} ({int(a.k_sig_neg)}) & {num(b_['mean'])} & [{num(b_.ci_lo)}, {num(b_.ci_hi)}] & {int(b_.k_neg)}/{int(b_.k)} ({int(b_.k_sig_neg)}) \\\\")
T += ["\\bottomrule", "\\end{tabular}\\endgroup}", ""]
open(f"{OUT}/stats_si_text.tex", "w").write("\n".join(T))
print("wrote", os.listdir(OUT))
